#!/usr/bin/env bash
# Writes the start-page scenes relief.terminal.yaml and relief-narrow.terminal.yaml from
# shop-clean.txt, the real output of
#   cargo run -p relief-cdp -- run spike/tasks/01-shop-clean.txt
# (2026-10-26, Google Chrome on macOS; the local path is replaced by file:///REPO/).
# Nothing is reworded: the scene takes three of the dialogue steps with their answers,
# without the timing and expectation lines, plus the summary line of the run.
# Rebuild the scenes afterwards:
#   cd site/captures && for f in relief.terminal.yaml relief-narrow.terminal.yaml; do
#     npx -y -p @casoon/castwright@0.4.0 -p shiki castwright build "$f" --format svg --loop-delay 12000 -o .; done
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
run="$here/shop-clean.txt"

# step <input>: the "> <input>" line (bold cyan) and its indented answer lines.
step() {
  awk -v want="> $1" '
    $0 == want { on = 1; printf "\033[1;36m%s\033[0m\n", $0; next }
    on && /^  [^✓]/ { print; next }
    on { exit }
  ' "$run"
}

excerpt="$(
  step 'Öffne den Warenkorb'
  echo
  step 'klicke In den Warenkorb'
  echo
  step 'klicke Jetzt kaufen'
  echo
  grep '^Erwartungen:' "$run" | sed 's/.*/\x1b[1;32m&\x1b[0m/'
)"

# wrap <cols>: breaks long answer lines at spaces (counted in characters, not bytes) and
# indents the continuation like the line itself, so no word is split at the edge.
wrap() {
  perl -CSD -ne '
    chomp; my ($ind) = /^( *)/; my $w = '"$1"';
    (my $vis = $_) =~ s/\e\[[0-9;]*m//g;
    if (length($vis) <= $w) { print "$_\n"; next }
    my $line = "";
    for my $word (split / /, substr($_, length $ind)) {
      my $cand = $line eq "" ? $word : "$line $word";
      if (length($ind) + length($cand) > $w && $line ne "") { print "$ind$line\n"; $line = $word }
      else { $line = $cand }
    }
    print "$ind$line\n";
  '
}

# One YAML double-quoted string: ESC as \e, line ends as \r\n, quotes and backslashes escaped.
raw() {
  printf '%s\n' "$excerpt" | wrap "$1" | perl -0pe 's/\\/\\\\/g; s/"/\\"/g; s/\e/\\e/g; s/\n/\\r\\n/g; $_ = "\"$_\""'
}

# scene <file> <cols> <rows>: the same steps, wrapped for <cols>; the narrow one is for phones,
# so the text keeps its size instead of shrinking.
scene() {
  cat > "$here/$1" <<YAML
# Generated by excerpt.sh from shop-clean.txt: an excerpt of a real relief-cdp run.
# Edit excerpt.sh, not this file.
version: 1
terminal:
  title: relief-cdp
  cols: $2
  rows: $3
  theme: catppuccin-mocha
steps:
  - run: cargo run -p relief-cdp -- run spike/tasks/01-shop-clean.txt
  - wait: 800
  - output:
      raw: $(raw "$2")
  - wait: 6000
YAML
}

scene relief.terminal.yaml 66 21
scene relief-narrow.terminal.yaml 48 26
